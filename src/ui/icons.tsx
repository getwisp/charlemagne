/** Wandelt ein Raster in zusammengefasste Rechtecke (je Zeile gleichfarbige Läufe). */
function toRects(rows: readonly string[]): { x: number; y: number; w: number; fill: string }[] {
  const rects: { x: number; y: number; w: number; fill: string }[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      if (ch !== '.') rects.push({ x, y, w: end - x, fill: PALETTE[ch] });
      x = end;
    }
  });
  return rects;
}

const cache = new Map<IconName, ReturnType<typeof toRects>>();

export function PixelIcon({ name, size = 16, title, className }: { name: IconName; size?: number; title?: string; className?: string }) {
  let rects = cache.get(name);
  if (!rects) {
    rects = toRects(ICONS[name]);
    cache.set(name, rects);
  }
  return (
    <svg
      className={`pixel-icon ${className ?? ''}`}
      width={size}
      height={size}
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      role={title ? 'img' : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
    >
      {rects.map((r, i) => (
        <rect key={i} x={r.x} y={r.y} width={r.w} height={1} fill={r.fill} />
      ))}
    </svg>
  );
}

export const PALETTE_CHARS = Object.keys(PALETTE);

/** Pixel-Symbol als SVG-Data-URI, z. B. für Mauszeiger. */
export function iconDataUri(name: IconName, size = 32): string {
  const body = toRects(ICONS[name])
    .map((r) => `<rect x='${r.x}' y='${r.y}' width='${r.w}' height='1' fill='${r.fill}'/>`)
    .join('');
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' width='${size}' height='${size}' viewBox='0 0 16 16' shape-rendering='crispEdges'>${body}</svg>`;
  return `data:image/svg+xml,${svg.replace(/#/g, '%23')}`;
}
